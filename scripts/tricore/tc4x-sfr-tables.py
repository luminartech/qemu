#!/usr/bin/env python3
#
# Generate hw/tricore/tc4x_sfr_tables.c, the register write semantics and
# kernel reset registers of the tc4x machine, from the TC4x SFR headers of
# Infineon's iLLD (Infra/Sfr/TC4DA/_Reg in any AURIX TC4x code example of
# https://github.com/Infineon/AURIX_code_examples):
#
#   scripts/tricore/tc4x-sfr-tables.py SFR_REG_DIR \
#       > hw/tricore/tc4x_sfr_tables.c
#
# Each bit field of the *_regdef.h headers carries its access type in its
# comment: rw1c/rw1ch bits clear when written with 1, rw0c/rw0ch with 0,
# rw1s/rw1sh bits set when written with 1, rw/rwh bits store the write,
# and write-only (w) bits, such as clear triggers, read as 0.  Registers
# with clearing, setting or write-only bits get an entry, in which only
# the rw/rwh bits store what is written; the machine stores every write to
# the other registers as it is.  Every module with RST_CTRLA/RST_CTRLB/
# RST_STAT registers gets a kernel reset entry.
#
# Copyright (c) 2026 MicroVision, Inc.
#
# SPDX-License-Identifier: GPL-2.0-or-later

import pathlib
import re
import sys

REGISTER = re.compile(r"#define (\w+) /\*.*?\*/ "
                      r"\(\*\(volatile (Ifx_\w+)\*\)0x([0-9A-Fa-f]+)u\)")
STRUCT = re.compile(r"typedef struct _(Ifx_\w+)_Bits\s*\{(.*?)\}", re.DOTALL)
# Descriptions may contain parentheses ("channel [x] ([x]:0...m-1) (rw1ch)"):
# the access type is the last "(word)" before the end of the comment.
BITFIELD = re.compile(r"Ifx_\w+ *\w*:(\d+);\s*"
                      r"/\*\*< \\brief \[(\d+):(\d+)\](.*?)\*/")
ACCESS = re.compile(r"\((\w+)\)\s*$")
# the machine's SFR regions; registers below are core-relative
SFR_SPACE = 0xE0000000
NOTICE = re.compile(r"\\copyright (Copyright .*?)\n.*?"
                    r"(Boost Software License.*?DEALINGS IN THE SOFTWARE\.)",
                    re.DOTALL)


def registers(reg_dir):
    for header in sorted(reg_dir.glob("*_reg.h")):
        text = header.read_text(errors="ignore")
        for name, reg_type, addr in REGISTER.findall(text):
            yield name, reg_type, int(addr, 16)


def access_masks(reg_dir):
    """{register type: (persist, w1c, w0c, w1s)} from the bit field comments"""
    kinds = {}
    for header in sorted(reg_dir.glob("*_regdef.h")):
        for name, body in STRUCT.findall(header.read_text(errors="ignore")):
            persist = w1c = w0c = w1s = wonly = 0
            for _width, hi, lo, text in BITFIELD.findall(body):
                match = ACCESS.search(text)
                if not match:
                    continue
                bits = ((1 << (int(hi) - int(lo) + 1)) - 1) << int(lo)
                access = match.group(1)
                if access in ("rw", "rwh"):
                    persist |= bits
                elif access in ("rw1c", "rw1ch"):
                    w1c |= bits
                elif access in ("rw0c", "rw0ch"):
                    w0c |= bits
                elif access in ("rw1s", "rw1sh"):
                    w1s |= bits
                elif access == "w":
                    wonly |= bits
            if w1c | w0c | w1s | wonly:
                kinds[name] = (persist & 0xFFFFFFFF, w1c, w0c, w1s)
    return kinds


def main():
    reg_dir = pathlib.Path(sys.argv[1])
    kinds = access_masks(reg_dir)
    words, names = {}, {}
    for name, reg_type, addr in registers(reg_dir):
        names.setdefault(name, addr)
        if reg_type in kinds and addr >= SFR_SPACE:
            # the machine keys semantics by word: the higher register wins
            words[addr & ~3] = kinds[reg_type]
    resets = []
    for name, ctrlb in sorted(names.items()):
        if name.endswith("_RST_CTRLB"):
            prefix = name[: -len("CTRLB")]
            if prefix + "CTRLA" in names and prefix + "STAT" in names:
                resets.append((names[prefix + "CTRLA"], ctrlb,
                               names[prefix + "STAT"]))
    asclin = (reg_dir / "IfxAsclin_reg.h").read_text(errors="ignore")
    notice = NOTICE.search(asclin)
    out = ["/*",
           " * SPDX" "-License-Identifier: GPL-2.0-or-later",
           " *",
           " * TC4x register write semantics and kernel reset registers,",
           " * generated by scripts/tricore/tc4x-sfr-tables.py from the SFR",
           " * headers of the Infineon iLLD, which carry this notice:",
           " *"]
    for line in (notice.group(1) + "\n\n" + notice.group(2)).splitlines():
        line = line.lstrip(" *").rstrip()
        out.append(f" * {line}".rstrip())
    out += [" */",
            "",
            '#include "qemu/osdep.h"',
            '#include "hw/tricore/tc4x_board.h"',
            "",
            "const Tc4xRegSemantics tc4x_reg_semantics[] = {"]
    out += [f"    {{ {a:#x}, {p:#x}, {c1:#x}, {c0:#x}, {s1:#x} }},"
            for a, (p, c1, c0, s1) in sorted(words.items())]
    out += ["};",
            "const size_t tc4x_n_reg_semantics =",
            "    ARRAY_SIZE(tc4x_reg_semantics);",
            "",
            "const Tc4xKernelReset tc4x_kernel_resets[] = {"]
    out += [f"    {{ {a:#x}, {b:#x}, {c:#x} }}," for a, b, c in resets]
    out += ["};",
            "const size_t tc4x_n_kernel_resets =",
            "    ARRAY_SIZE(tc4x_kernel_resets);",
            ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
